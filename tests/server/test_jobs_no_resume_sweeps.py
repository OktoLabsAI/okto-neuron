def test_second_rehydrate_is_idempotent(tmp_path: Path) -> None:
    root = tmp_path / "vault"
    _persist_job(root, "predicate-propose", "running")
    first = _state(root)
    _jobs.rehydrate_jobs(first)
    snapshot = _jobs.jobs_path(first).read_text(encoding="utf-8")
    second = _state(root)
    _jobs.rehydrate_jobs(second)
    assert _jobs.jobs_path(second).read_text(encoding="utf-8") == snapshot
    assert second.curation_jobs[0].error == REASON
    assert second.curation_jobs[0].finished_at == first.curation_jobs[0].finished_at


def test_linked_d8_ingest_outcome_is_failed_and_persisted(tmp_path: Path) -> None:
    root = tmp_path / "vault"
    state = _state(root)
    job = _jobs.new_job(
        "reconcile-propose",
        params={"trigger": "verified_file_commit", "ingest_item_ids": ["ingest-1"]},
    )
    job.status = "running"
    state.curation_jobs = [job]
    _jobs.persist(state)
    state.ingest_queue = [
        IngestItem(
            id="ingest-1",
            name="book.md",
            path="/book.md",
            status="done",
            outcome={
                "quality": "complete",
                "cross_document_reconciliation": {
                    "state": "scheduled",
                    "job_id": job.id,
                    "trigger": "verified_file_commit",
                    "coalesced": False,
                },
            },
        ),
        IngestItem(  # a retried item whose link points at a different job is left alone
            id="ingest-2",
            name="b.md",
            path="/b.md",
            status="done",
            outcome={"cross_document_reconciliation": {"state": "scheduled", "job_id": "other"}},
        ),
    ]
    _ingest_queue.persist(state)

    # Real startup order: ingest queue first, then the jobs.
    fresh = _state(root)
    _ingest_queue.rehydrate_queue(fresh)
    _jobs.rehydrate_jobs(fresh)

    item = fresh.ingest_queue[0]
    assert item.status == "done"  # the graph commit itself stays done
    linked = item.outcome["cross_document_reconciliation"]
    assert linked["state"] == "failed"
    assert linked["job_id"] == job.id
    assert linked["error"] == REASON
    assert fresh.ingest_queue[1].outcome["cross_document_reconciliation"]["state"] == "scheduled"

    on_disk = json.loads(_ingest_queue.history_path(fresh).read_text(encoding="utf-8"))
    persisted = {i["id"]: i for i in on_disk["items"]}
    assert persisted["ingest-1"]["outcome"]["cross_document_reconciliation"]["state"] == "failed"
    assert persisted["ingest-1"]["outcome"]["cross_document_reconciliation"]["error"] == REASON
