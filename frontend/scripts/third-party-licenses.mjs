// Writes ../frontend_dist/THIRD_PARTY_LICENSES.txt after `vite build`.
//
// The built UI bundles the non-dev npm packages listed in package-lock.json.
// Their licenses require the license text to travel with the code, and
// frontend_dist/ ships inside the wheel as okto_neuron/_webui, so the texts are
// collected here from node_modules (installed by `npm ci`) and written next to
// the bundle. The output is sorted and has no timestamps, so a rebuild from the
// same lockfile is byte-identical.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.resolve(frontend, "../frontend_dist/THIRD_PARTY_LICENSES.txt");
const lock = JSON.parse(readFileSync(path.join(frontend, "package-lock.json"), "utf8"));

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;

const entries = [];
for (const [lockPath, meta] of Object.entries(lock.packages ?? {})) {
  if (!lockPath || meta.dev || meta.devOptional) continue;
  const dir = path.join(frontend, lockPath);
  if (!existsSync(dir)) {
    throw new Error(`${lockPath} is in package-lock.json but not installed; run npm ci first`);
  }
  const pkg = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8"));
  const licenseFiles = readdirSync(dir)
    .filter((name) => LICENSE_FILE.test(name))
    .sort();
  if (licenseFiles.length === 0) {
    throw new Error(`${pkg.name}@${pkg.version} ships no LICENSE/NOTICE file`);
  }
  const texts = licenseFiles.map((name) => readFileSync(path.join(dir, name), "utf8").trim());
  entries.push({ name: pkg.name, version: pkg.version, license: pkg.license ?? meta.license, texts });
}
entries.sort((a, b) => (a.name + "@" + a.version).localeCompare(b.name + "@" + b.version));

const rule = "=".repeat(78);
const parts = [
  "Okto Neuron web UI: third-party licenses",
  "",
  "The files in this directory bundle the npm packages below. Each is used",
  "under its own license, reproduced here from the published package.",
  "Generated by frontend/scripts/third-party-licenses.mjs from package-lock.json.",
  "",
];
for (const entry of entries) {
  parts.push(rule, `${entry.name} ${entry.version} (${entry.license})`, rule, "");
  for (const text of entry.texts) parts.push(text, "");
}
writeFileSync(outFile, parts.join("\n").replace(/\n+$/, "\n"), "utf8");
console.log(`wrote ${path.relative(path.resolve(frontend, ".."), outFile)} (${entries.length} packages)`);
